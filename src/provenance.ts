// Signed provenance (§7b Part 3). Agents sign sha256(canonical JSON of the payload) with their uAgents identity
// (secp256k1 ECDSA over the digest, bech32 "sig1..."); addresses are bech32 "agent1..." of the compressed pubkey.
// The backend verifies before writing and only accepts signers on the Rosetta allowlist.
import "dotenv/config";
import { createHash } from "node:crypto";
import { secp256k1 } from "@noble/curves/secp256k1.js";
import { bech32 } from "@scure/base";

export type Verified = true | false | "tampered" | "unsigned-fallback" | "unknown-signer";
export type SignedEnvelope<T = unknown> = { payload: T; payloadHash: string; signer: string; signature: string };

/** Canonical JSON: object keys sorted recursively, no whitespace. Must match agents/signing.py. */
export function canonical(x: unknown): string {
  if (x === null || typeof x !== "object") return JSON.stringify(x);
  if (Array.isArray(x)) return `[${x.map(canonical).join(",")}]`;
  const o = x as Record<string, unknown>;
  return `{${Object.keys(o).filter((k) => o[k] !== undefined).sort().map((k) => `${JSON.stringify(k)}:${canonical(o[k])}`).join(",")}}`;
}

export const payloadHash = (payload: unknown) => createHash("sha256").update(canonical(payload)).digest("hex");

function decode(prefix: string, s: string): Uint8Array {
  const d = bech32.decode(s as `${string}1${string}`, 1023);
  if (d.prefix !== prefix) throw new Error(`expected ${prefix} prefix`);
  return bech32.fromWords(d.words);
}

/** name -> address, from AGENT_ADDR_* in .env (generated by agents/keys.py). */
export const ALLOWLIST: Record<string, string> = Object.fromEntries(
  Object.entries(process.env).filter(([k, v]) => k.startsWith("AGENT_ADDR_") && v).map(([k, v]) => [k.slice(11).toLowerCase(), v!]),
);
export const nameOf = (address: string) => Object.entries(ALLOWLIST).find(([, a]) => a === address)?.[0];

export function verifySignature(address: string, hashHex: string, signature: string): boolean {
  try {
    const pub = decode("agent", address);
    const sig = decode("sig", signature);
    // python-ecdsa does not normalize s, so accept high-s signatures; digest is already sha256 -> no prehash
    return secp256k1.verify(sig, Buffer.from(hashHex, "hex"), pub, { prehash: false, lowS: false, format: "compact" });
  } catch {
    return false;
  }
}

/** Full check of an envelope: allowlisted signer, hash matches payload, signature valid. */
export function verifyEnvelope(env: SignedEnvelope, expectedSigner?: string): { verified: Verified; signerName?: string; reason?: string } {
  const signerName = nameOf(env.signer);
  if (!signerName) return { verified: "unknown-signer", reason: "signer not in Rosetta allowlist" };
  if (expectedSigner && signerName !== expectedSigner) return { verified: false, signerName, reason: `expected ${expectedSigner}, signed by ${signerName}` };
  if (payloadHash(env.payload) !== env.payloadHash) return { verified: "tampered", signerName, reason: "payload hash mismatch" };
  if (!verifySignature(env.signer, env.payloadHash, env.signature)) return { verified: false, signerName, reason: "bad signature" };
  return { verified: true, signerName };
}
